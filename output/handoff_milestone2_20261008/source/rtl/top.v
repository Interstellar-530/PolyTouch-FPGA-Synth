// Milestone 3: four-voice polyphonic instrument on the Tang Primer 20K Dock.
//
//   song_player -> event FIFO -> voice allocator -> 4x poly_voice -> mixer
//                    ^
//                    +--- uart_ctrl (the keyboard interface, for now)
//
// Every voice owns a phase accumulator, a frequency control word and an
// envelope, and the four voices are summed with saturation, which is the
// minimum the competition asks for.  The note event bus is the seam a real
// performance keyboard plugs into: the MPR121 touch controller will drive
// exactly the same {valid, on, note, velocity} signals the UART controller
// drives today, and nothing downstream changes.
//
// Keys: S1 toggles the chord set A/B, S2 changes tempo, S3 resets.
// UART 115200 8N1 on M11/T13: N<note> note on, O<note> note off, X all off,
// M0/M1 mute, D0 manual mode, D1 demo mode. N/O/X enter manual mode.
module top (
    input  wire clk_27m,
    input  wire key_rst,     // S3 / D7, active-low design reset
    input  wire key_s1,      // S1 / T3, active-low, chord set A/B
    input  wire key_s2,      // S2 / T2, active-low, restart the test tune
    input  wire uart_rx,     // T13, from BL702 UART1_TX
    output wire hp_bck,
    output wire hp_ws,
    output wire hp_din,
    output wire pa_en,
    output wire led,         // N16, run indicator
    output wire led_chord,   // N14, lit while chord set B is selected
    output wire led_t0,      // L14, tempo preset bit 0
    output wire led_t1,      // L16, tempo preset bit 1
    output wire uart_tx      // M11, to BL702 UART1_RX
);

    // ------------------------------------------------------- reset tree ---
    // The power-on reset releases about 2.4 ms after configuration.  The
    // headphone amplifier enable follows it only, so a design reset never
    // mutes the amplifier and never produces a pop.
    wire sample_tick;          // 46.875 kHz tick, generated by pt8211_tx

    // Explicit power-up values.  The FPGA itself starts every register at zero,
    // but saying so here keeps the RTL simulation deterministic as well: an
    // uninitialised reset_cnt would compare as x and the power-on reset would
    // never complete.
    reg [15:0] reset_cnt = 16'd0;
    always @(posedge clk_27m)
        if (reset_cnt != 16'hFFFF)
            reset_cnt <= reset_cnt + 1'b1;

    wire por = (reset_cnt != 16'hFFFF);
    assign pa_en = ~por;

    // S3 on D7 is a plain 1.5 V user IO; S0/T10 is reserved for the
    // configuration SSPI and S4/B10 is RECONFIG_N, so neither can be used.
    reg [1:0] rst_key_sync = 2'b11;
    always @(posedge clk_27m)
        rst_key_sync <= {rst_key_sync[0], key_rst};

    wire soft_rst = ~rst_key_sync[1];
    wire rst      = por | soft_rst;

    // ------------------------------------------------------ user keys -----
    reg [1:0] s1_sync = 2'b11;
    reg [1:0] s2_sync = 2'b11;
    always @(posedge clk_27m) begin
        s1_sync <= {s1_sync[0], key_s1};
        s2_sync <= {s2_sync[0], key_s2};
    end

    wire s1_pressed = ~s1_sync[1];
    wire s2_pressed = ~s2_sync[1];

    localparam [19:0] DEBOUNCE_MAX = 20'hFFFFF;   // about 38.8 ms at 27 MHz

    reg [19:0] db1_cnt, db2_cnt;
    reg        s1_stable, s2_stable;

    always @(posedge clk_27m) begin
        if (rst) begin
            db1_cnt   <= 20'd0;
            db2_cnt   <= 20'd0;
            s1_stable <= 1'b0;
            s2_stable <= 1'b0;
        end else begin
            if (!s1_pressed) begin
                db1_cnt   <= 20'd0;
                s1_stable <= 1'b0;
            end else if (db1_cnt == DEBOUNCE_MAX) begin
                s1_stable <= 1'b1;
            end else begin
                db1_cnt <= db1_cnt + 1'b1;
            end

            if (!s2_pressed) begin
                db2_cnt   <= 20'd0;
                s2_stable <= 1'b0;
            end else if (db2_cnt == DEBOUNCE_MAX) begin
                s2_stable <= 1'b1;
            end else begin
                db2_cnt <= db2_cnt + 1'b1;
            end
        end
    end

    reg s1_stable_d, s2_stable_d;
    always @(posedge clk_27m) begin
        s1_stable_d <= s1_stable;
        s2_stable_d <= s2_stable;
    end

    wire s1_press = s1_stable & ~s1_stable_d;
    wire s2_press = s2_stable & ~s2_stable_d;

    // S1 selects between the two harmonisations.  S2 steps through the four
    // tempo presets, stretching every note slot by 1x .. 4x, and restarts the
    // tune so the change is heard immediately.  The two spare LEDs show the
    // preset in binary, which makes it possible to report back "preset 2 is
    // right" instead of guessing.
    reg chord_set;
    reg restart;
    reg [1:0] tempo_sel;

    always @(posedge clk_27m) begin
        if (por) begin
            chord_set <= 1'b0;
            restart   <= 1'b0;
            // Preset index 1 (2x) is the state that was reported as the right
            // playback speed: L14 lit, L16 dark.  The LEDs are active low and
            // driven as ~tempo_sel[bit], so a lit LED means that bit is one.
            // S2 steps through all four presets.
            tempo_sel <= 2'd1;
        end else begin
            if (s1_press)
                chord_set <= ~chord_set;
            if (s2_press)
                tempo_sel <= tempo_sel + 2'd1;   // wraps 3 -> 0
            restart <= s2_press;
        end
    end

    // ------------------------------------------------------- note events ---
    wire        sp_ev_wr;
    wire [15:0] sp_ev_data;
    wire [5:0]  mel_idx_dbg;
    wire        fifo_empty;
    wire        fifo_full;
    wire        fifo_ready;
    wire [15:0] fifo_data;
    wire        fifo_rd;
    wire        uart_ev_valid, uart_ev_on, uart_panic, uart_muted;
    wire        uart_demo_on, uart_demo_off;
    wire [6:0]  uart_ev_note;
    wire [7:0]  uart_ev_vel;

    reg         demo_mode;
    reg         pending_valid;
    reg [15:0]  pending_word;
    wire        manual_transition = demo_mode && (uart_ev_valid || uart_panic);
    wire        clear_events = uart_demo_on || uart_demo_off ||
                               manual_transition || uart_panic || (restart && demo_mode);

    always @(posedge clk_27m) begin
        if (rst) begin
            demo_mode     <= 1'b1; // preserve power-on song demonstration
            pending_valid <= 1'b0;
            pending_word  <= 16'd0;
        end else begin
            pending_valid <= 1'b0;
            if (uart_demo_on)
                demo_mode <= 1'b1;
            else if (uart_demo_off || manual_transition)
                demo_mode <= 1'b0;
            // The first manual event is replayed after the old demo voices
            // have been released; otherwise panic would swallow that note.
            if (manual_transition && uart_ev_valid) begin
                pending_valid <= 1'b1;
                pending_word  <= {uart_ev_on, uart_ev_note, uart_ev_vel};
            end
        end
    end

    song_player u_song (
        .clk          (clk_27m),
        .rst          (rst | ~demo_mode),
        .sample_tick  (sample_tick),
        .restart      (restart | uart_demo_on),
        .chord_set    (chord_set),
        .tempo_sel    (tempo_sel),
        .ev_ready     (fifo_ready),
        .ev_wr        (sp_ev_wr),
        .ev_data      (sp_ev_data),
        .mel_idx_dbg  (mel_idx_dbg),
        .chord_idx_dbg()
    );

    // ------------------------------------------------------- loop marker ---
    // The melody index wraps from the last note back to the first once per
    // pass.  Flashing an LED at that moment turns "the tune repeats too soon"
    // into something that can be measured with a stopwatch instead of argued
    // about: the loop is 32.5 s at preset 1 and doubles with each step.
    reg [5:0]  mel_idx_d;
    reg [21:0] loop_blink_cnt;
    reg        loop_blink;

    always @(posedge clk_27m) begin
        if (por) begin
            mel_idx_d      <= 6'd0;
            loop_blink_cnt <= 22'd0;
            loop_blink     <= 1'b0;
        end else begin
            mel_idx_d <= mel_idx_dbg;
            if ((mel_idx_dbg == 6'd0) && (mel_idx_d != 6'd0)) begin
                loop_blink_cnt <= 22'd3_000_000;   // about 111 ms
                loop_blink     <= 1'b1;
            end else if (loop_blink_cnt != 22'd0) begin
                loop_blink_cnt <= loop_blink_cnt - 22'd1;
                if (loop_blink_cnt == 22'd1)
                    loop_blink <= 1'b0;
            end
        end
    end

    event_fifo u_fifo (
        .clk     (clk_27m),
        .rst     (rst | clear_events),
        .wr_en   (sp_ev_wr & demo_mode),
        .wr_data (sp_ev_data),
        .rd_en   (fifo_rd),
        .rd_data (fifo_data),
        .empty   (fifo_empty),
        .full    (fifo_full),
        .wr_ready(fifo_ready)
    );

    uart_ctrl u_uart (
        .clk      (clk_27m),
        .rst      (rst),
        .uart_rx  (uart_rx),
        .uart_tx  (uart_tx),
        .ev_valid (uart_ev_valid),
        .ev_on    (uart_ev_on),
        .ev_note  (uart_ev_note),
        .ev_vel   (uart_ev_vel),
        .panic    (uart_panic),
        .muted    (uart_muted),
        .demo_on  (uart_demo_on),
        .demo_off (uart_demo_off)
    );

    // Panic and mode changes clear stale demo events before dispatch.  UART
    // Note Off has the same priority as Note On during manual performance.
    wire        uart_direct = uart_ev_valid && !manual_transition;
    wire        ev_valid = !clear_events &&
                           (pending_valid || uart_direct || (demo_mode && !fifo_empty));
    wire [15:0] ev_word  = pending_valid ? pending_word :
                           uart_direct ? {uart_ev_on, uart_ev_note, uart_ev_vel} : fifo_data;
    assign fifo_rd = demo_mode && !clear_events && !pending_valid &&
                     !uart_direct && !fifo_empty;

    // ---------------------------------------------------- voice control ---
    wire [3:0]  v_gate;
    wire [27:0] v_note;      // 4 x 7 bit
    wire [31:0] v_vel;       // 4 x 8 bit
    wire [3:0]  v_idle;
    wire [3:0]  v_start;

    voice_alloc u_alloc (
        .clk        (clk_27m),
        .rst        (rst),
        .ev_valid   (ev_valid),
        .ev_on      (ev_word[15]),
        .ev_note    (ev_word[14:8]),
        .ev_vel     (ev_word[7:0]),
        .panic      (clear_events),
        .voice_idle (v_idle),
        .v_gate     (v_gate),
        .v_note     (v_note),
        .v_vel      (v_vel),
        .v_start    (v_start),
        .v_busy     ()
    );

    // ----------------------------------------------------------- voices ---
    wire signed [15:0] vs0, vs1, vs2, vs3;
    wire [31:0] inc0, inc1, inc2, inc3;

    note_phase_inc u_inc0 (.note(v_note[6:0]),   .inc(inc0));
    note_phase_inc u_inc1 (.note(v_note[13:7]),  .inc(inc1));
    note_phase_inc u_inc2 (.note(v_note[20:14]), .inc(inc2));
    note_phase_inc u_inc3 (.note(v_note[27:21]), .inc(inc3));

    poly_voice u_v0 (
        .clk (clk_27m), .rst (rst), .sample_tick (sample_tick),
        .gate (v_gate[0]), .start (v_start[0]), .phase_inc (inc0), .velocity (v_vel[7:0]),
        .sample (vs0), .idle (v_idle[0])
    );
    poly_voice u_v1 (
        .clk (clk_27m), .rst (rst), .sample_tick (sample_tick),
        .gate (v_gate[1]), .start (v_start[1]), .phase_inc (inc1), .velocity (v_vel[15:8]),
        .sample (vs1), .idle (v_idle[1])
    );
    poly_voice u_v2 (
        .clk (clk_27m), .rst (rst), .sample_tick (sample_tick),
        .gate (v_gate[2]), .start (v_start[2]), .phase_inc (inc2), .velocity (v_vel[23:16]),
        .sample (vs2), .idle (v_idle[2])
    );
    poly_voice u_v3 (
        .clk (clk_27m), .rst (rst), .sample_tick (sample_tick),
        .gate (v_gate[3]), .start (v_start[3]), .phase_inc (inc3), .velocity (v_vel[31:24]),
        .sample (vs3), .idle (v_idle[3])
    );

    // ------------------------------------------------------------ mixer ---
    wire signed [15:0] mixed;
    mixer u_mixer (
        .clk (clk_27m), .rst (rst), .sample_tick (sample_tick),
        .v0 (vs0), .v1 (vs1), .v2 (vs2), .v3 (vs3),
        .sample_out (mixed)
    );

    // M0 from the host forces a digital zero so the listener can tell digital
    // content apart from board-level noise.
    wire signed [15:0] final_sample = (rst | uart_muted) ? 16'sd0 : mixed;

    pt8211_tx u_pt8211 (
        .clk         (clk_27m),
        .rst         (por),
        .sample_in   (final_sample),
        .bck         (hp_bck),
        .ws          (hp_ws),
        .din         (hp_din),
        .sample_tick (sample_tick)
    );

    // ---------------------------------------------------------- display ---
    // The user LEDs are active low.  N16 is the loop marker: it lights for
    // about 110 ms at the start of every pass through the tune, and stays lit
    // while the output is muted.  Timing the gap between flashes measures the
    // loop directly.  N14 shows the chord set, L14/L16 the tempo preset.
    assign led       = uart_muted ? 1'b0 : ~loop_blink;
    assign led_chord = ~chord_set;
    assign led_t0    = ~tempo_sel[0];
    assign led_t1    = ~tempo_sel[1];

endmodule
