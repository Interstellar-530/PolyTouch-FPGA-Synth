"""Generate the independent 88-key CH9350L layout; Python standard library only."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def layout():
    groups = [
        ("Original lower", "Z S X D C V G B H N J M".split(),
         [0x1D, 0x16, 0x1B, 0x07, 0x06, 0x19, 0x0A, 0x05, 0x0B, 0x11, 0x0D, 0x10], 48),
        ("Original upper", "Q 2 W 3 E R 5 T 6 Y 7 U".split(),
         [0x14, 0x1F, 0x1A, 0x20, 0x08, 0x15, 0x22, 0x17, 0x23, 0x1C, 0x24, 0x18], 60),
        ("Upper extension", ["I", "9", "O", "0", "P", "[", "=", "]", "\\"],
         [0x0C, 0x26, 0x12, 0x27, 0x13, 0x2F, 0x2E, 0x30, 0x31], 72),
        ("Independent bass modifiers", ["LCtrl", "LShift", "LAlt", "LWin", "RCtrl", "RShift", "RAlt", "RWin"],
         list(range(0xE0, 0xE8)), 40),
        ("Numpad bass", ["KP0", "KP1", "KP2", "KP3", "KP4", "KP5", "KP6", "KP7", "KP8", "KP9", "KP.", "KP+", "KP-", "KP*", "KP/", "KPEnter"],
         [0x62, 0x59, 0x5A, 0x5B, 0x5C, 0x5D, 0x5E, 0x5F, 0x60, 0x61, 0x63, 0x57, 0x56, 0x55, 0x54, 0x58], 24),
        ("Additional typing keys", ["A", "F", "K", "L", ";", "'", ",", ".", "/", "`", "1", "4", "8", "-"],
         [0x04, 0x09, 0x0E, 0x0F, 0x33, 0x34, 0x36, 0x37, 0x38, 0x35, 0x1E, 0x21, 0x25, 0x2D], 81),
        ("Navigation high", ["Insert", "Home", "Delete", "End", "Left", "Right"],
         [0x49, 0x4A, 0x4C, 0x4D, 0x50, 0x4F], 95),
        ("Auxiliary high", ["Tab", "CapsLock", "Backspace", "Enter"], [0x2B, 0x39, 0x2A, 0x28], 101),
        ("Function high", ["F9", "F10", "F11", "F12"], [0x42, 0x43, 0x44, 0x45], 105),
        ("Lowest auxiliary", ["PrintScreen", "ScrollLock", "Pause"], [0x46, 0x47, 0x48], 21),
    ]
    rows = []
    for group, labels, usages, first in groups:
        assert len(labels) == len(usages)
        for i, (label, usage) in enumerate(zip(labels, usages)):
            rows.append(dict(group=group, key=label, usage=usage, midi=first+i))
    assert len(rows) == 88
    assert len({r['usage'] for r in rows}) == 88
    assert sorted(r['midi'] for r in rows) == list(range(21, 109))
    return rows


def main():
    rows = layout()
    text = ["// Generated by tools/gen_keyboard_layout.py. Event mapping, not audio waveform ROM.",
            "function [7:0] key_note;", "    input [7:0] k;", "    begin", "        case (k)"]
    for r in rows:
        text.append(f"            8'h{r['usage']:02X}: key_note = 8'd{r['midi']}; // {r['key']}")
    text += ["            default: key_note = 8'd0;", "        endcase", "    end", "endfunction", ""]
    (ROOT / 'rtl/audio/hid_note_map.vh').write_text('\n'.join(text), encoding='utf-8')
    (ROOT / 'tools/keyboard_layout.json').write_text(json.dumps(rows, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    table = ['| Key | HID usage | MIDI at base 60 |', '|---|---|---|']
    for r in rows:
        table.append(f"| {r['key']} | 0x{r['usage']:02X} | {r['midi']} |")
    (ROOT / 'tools/keyboard_layout.md').write_text('\n'.join(table)+'\n', encoding='utf-8')
    print('Generated 88 unique physical keys and MIDI notes 21..108; modifiers included.')


if __name__ == '__main__':
    main()
