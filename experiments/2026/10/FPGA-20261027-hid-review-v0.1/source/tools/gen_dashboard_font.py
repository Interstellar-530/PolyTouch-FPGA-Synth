def glyph_bytes(ch: str) -> bytes:
    rows = GLYPHS.get(ch, ["00000"] * 7)
    out = bytearray()
    for r in range(8):
        bits = rows[r] if r < 7 else "00000"
        # Centre the 5-pixel glyph in an 8-pixel row, with bit 7 as the leftmost pixel.
        value = 0
        for i, bit in enumerate(bits):
            if bit == "1":
                value |= 1 << (6 - i)
        out.append(value)
    return bytes(out)

data = bytearray()
for code in range(32, 96):
    data.extend(glyph_bytes(chr(code)))

if len(data) != 512:
    raise SystemExit(f"expected 512 bytes, got {len(data)}")

# pROM INIT_RAM words are 256-bit blocks, byte 0 in the least significant byte.
init = []
for block in range(16):
    chunk = data[block * 32:(block + 1) * 32]
    word = sum(value << (8 * index) for index, value in enumerate(chunk))
    init.append(f"        .INIT_RAM_{block:02X}(256'h{word:064X})")
init_text = ",\n".join(init)

