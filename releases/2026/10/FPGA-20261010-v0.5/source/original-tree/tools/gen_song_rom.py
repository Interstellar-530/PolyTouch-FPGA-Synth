"""Write the song tables and the note table constants.

Run from the source root:
    python tools/gen_song_rom.py

It writes rtl/audio/song_roms.vh, which song_player.v includes inside its
module body.  The tables are emitted as constant case functions rather than as
$readmemh initialised arrays: the tables are tiny (41 and 9 entries), and a
case function is plain combinational logic, so nothing depends on how the
synthesiser happens to map an initialised RAM.  Earlier builds inferred the
tables as internal RAM, and a partially initialised RAM would make the tune run
through a few phrases and then stall or repeat.

It also prints the twelve note_phase_inc base constants so the Verilog table
can be checked against the model.
"""

import os

import song_data


def hex_words(entries, width_bits):
    digits = width_bits // 4
    return [f"{value:0{digits}x}" for value in entries]


def write_vh(path):
    melody = hex_words(song_data.melody_rom_image(), 16)
    chord_a = hex_words(song_data.chord_rom_image("A"), 16)
    chord_b = hex_words(song_data.chord_rom_image("B"), 16)

    out = []
    out.append("// Generated by tools/gen_song_rom.py -- do not edit by hand.")
    out.append("//")
    out.append("// Melody word: {velocity_code[2:0], note[6:0], sounding_units[5:0]}")
    out.append("// Chord word : {root[7:0], slot_units[5:0], quality[1:0]}")
    out.append("")
    out.append("function [15:0] mel_word;")
    out.append("    input [5:0] idx;")
    out.append("    begin")
    out.append("        case (idx)")
    for index, word in enumerate(melody):
        out.append(f"            6'd{index}: mel_word = 16'h{word};")
    out.append("            default: mel_word = 16'h0000;")
    out.append("        endcase")
    out.append("    end")
    out.append("endfunction")
    out.append("")

    for name, table in (("chord_a_word", chord_a), ("chord_b_word", chord_b)):
        out.append(f"function [15:0] {name};")
        out.append("    input [3:0] idx;")
        out.append("    begin")
        out.append("        case (idx)")
        for index, word in enumerate(table):
            out.append(f"            4'd{index}: {name} = 16'h{word};")
        out.append(f"            default: {name} = 16'h0000;")
        out.append("        endcase")
        out.append("    end")
        out.append("endfunction")
        out.append("")

    with open(path, "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(out))
    print(f"wrote {path}: {len(melody)} melody words, "
          f"{len(chord_a)} chord words per set")


def main():
    issues = song_data.check()
    if issues:
        for issue in issues:
            print("FAIL:", issue)
        raise SystemExit(1)

    here = os.path.dirname(os.path.abspath(__file__))
    rtl = os.path.normpath(os.path.join(here, "..", "rtl", "audio"))
    write_vh(os.path.join(rtl, "song_roms.vh"))

    # note_phase_inc base table: phase_inc = round(f * 2^32 / 46875) for the
    # twelve semitones starting at MIDI 0 (C-1).
    scale = 2.0 ** (1.0 / 12.0)
    f0 = 440.0 * (2.0 ** ((0 - 69) / 12.0))
    factor = (2 ** 32) / song_data.SAMPLE_RATE
    print("note_phase_inc base constants (MIDI 0..11):")
    for i in range(12):
        value = int(round(f0 * (scale ** i) * factor))
        if value > 0xFFFFFFFF:
            raise SystemExit("base constant overflows 32 bits")
        print(f"  4'd{i:<2d}: base = 32'd{value};")


if __name__ == "__main__":
    main()
