"""Generate the local Kuanggu bridge event table; no audio waveform storage."""
from pathlib import Path
import song_kuanggu as score


def generate():
    assert not score.check(), score.check()
    notes = sorted(score.MELODY + [n for group in score.LEGATO for n in group])
    events = []
    cursor = 0
    for bar, unit, note, length in notes:
        start = bar * 16 + unit
        assert start >= cursor, (start, cursor)
        if start > cursor:
            events.append((0, start - cursor))
        events.append((note, length))
        cursor = start + length
    if cursor < score.TOTAL_UNITS:
        events.append((0, score.TOTAL_UNITS - cursor))
    assert sum(length for _, length in events) == 208
    assert len(events) < 256 and all(0 < length < 64 for _, length in events)
    chords = []
    for chord in score.CHORDS:
        root, third, fifth = chord
        assert fifth == root + 7 and third - root in (3, 4)
        chords.append((root << 8) | (16 << 2) | (third - root == 3))
    out = ['// Generated by tools/gen_second_song.py from song_kuanggu.py.',
           f'localparam [7:0] SECOND_MELODY_LAST = 8\'d{len(events)-1};',
           f'localparam [5:0] SECOND_CHORD_LAST = 6\'d{len(chords)-1};']
    for name, width, words in (
        ('second_mel_word', 8, [((5 if n else 0) << 13) | (n << 6) | length for n, length in events]),
        ('second_chord_word', 6, chords)):
        out += [f'function [15:0] {name};', f'    input [{width-1}:0] idx;',
                '    begin', '        case (idx)']
        out += [f"            {width}'d{i}: {name} = 16'h{word:04x};" for i, word in enumerate(words)]
        out += [f"            default: {name} = 16'h0000;", '        endcase', '    end', 'endfunction']
    path = Path(__file__).resolve().parents[1] / 'rtl/audio/song_second_roms.vh'
    path.write_text('\n'.join(out) + '\n', encoding='ascii')
    print(f'{len(events)} melody entries, {sum(n != 0 for n, _ in events)} notes, {len(chords)} chords, 208 units')


if __name__ == '__main__':
    generate()
