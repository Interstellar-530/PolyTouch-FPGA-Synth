"""Build the compacted AKWF electric-piano bank (2 zone groups x 6 stages = 12 tables, 6 BSRAM).

The six keyboard zones only differ in their band limit, but the source AKWF
e-piano keeps ~12 harmonics, so zones 0..4 produce the same tables up to float
rounding (-73 dB or lower). This script therefore emits two groups:
  group 0 -> zones 0..4 (band limit of zone 0, 170 harmonics)
  group 1 -> zone 5     (band limit of zone 5, 10 harmonics; needed so notes up
                         to MIDI 95 stay below Nyquist)
Bank index = group*6 + stage, exactly what shared_wavetable_engine maps.
"""
import argparse
from pathlib import Path
import json
import wave
import numpy as np

REPO = Path(__file__).resolve().parents[1]
DEFAULT_AUDIO = REPO / 'output/handoff_milestone2_20261008/source/rtl/audio'
DEFAULT_WAV = REPO / 'tmp/akwf/AKWF_epiano/AKWF_epiano_0001.wav'
FS = 46875
# MIDI edges for six keyboard zones; last note < 96.
EDGES = [0, 48, 60, 67, 76, 84, 96]
# group -> zone whose band limit is used
GROUPS = [0, 5]

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--repo-root', type=Path, default=REPO,
                    help='repository root used to resolve the default paths')
parser.add_argument('--wav', type=Path,
                    help='source AKWF wav (default: <repo-root>/tmp/akwf/AKWF_epiano/AKWF_epiano_0001.wav)')
parser.add_argument('--out-dir', type=Path,
                    help='generated output directory (default: <repo-root>/output/.../rtl/audio)')
args = parser.parse_args()
ROOT = args.repo_root.resolve()
AUDIO = (args.out_dir or ROOT / 'output/handoff_milestone2_20261008/source/rtl/audio').resolve()
SRC = (args.wav or ROOT / 'tmp/akwf/AKWF_epiano/AKWF_epiano_0001.wav').resolve()
if not SRC.is_file():
    raise SystemExit(f'source wav not found: {SRC} (pass --wav or --repo-root)')
AUDIO.mkdir(parents=True, exist_ok=True)


def midi_f(n):
    return 440.0 * 2.0 ** ((n - 69) / 12.0)


def read_wav(path):
    w = wave.open(str(path), 'rb')
    n, ch, sw, sr = w.getnframes(), w.getnchannels(), w.getsampwidth(), w.getframerate()
    raw = w.readframes(n)
    if sw != 2:
        raise ValueError(f'expected 16-bit, got {sw * 8}')
    d = np.frombuffer(raw, dtype='<i2').astype(float)
    d = d[:len(d) // ch * ch].reshape(-1, ch).mean(axis=1)
    return d, sr


def resample_periodic(d, n_out):
    """FFT resample one cycle to n_out points, keeping bins below both Nyquists."""
    d = d - d.mean()
    D = np.fft.rfft(d)
    n_in = len(d)
    out = np.zeros(n_out // 2 + 1, dtype=complex)
    k = min(len(D), len(out))
    out[:k] = D[:k]
    return np.fft.irfft(out, n_out) * (n_out / n_in)


src, sr = read_wav(SRC)
table0 = resample_periodic(src, 512)
print('source', SRC.name, 'sr', sr, 'samples', len(src), 'peak', int(np.max(np.abs(src))))

tables = []
meta = []
for group, zone in enumerate(GROUPS):
    fmax = midi_f(EDGES[zone + 1] - 1)
    hmax = max(1, min(240, int(0.45 * FS / fmax)))
    for s in range(6):
        # stage 5 = bright attack, stage 0 = soft body.
        alpha = 0.006 + 0.014 * (5 - s)
        spec = np.fft.rfft(table0)
        h = np.arange(len(spec))
        tilt = np.exp(-alpha * h)
        # E-piano bell: lift harmonics 2-4 a little on the bright stages.
        bell = 1.0 + 0.30 * (5 - s) / 5.0 * np.exp(-((h - 3.0) / 1.4) ** 2)
        spec = spec * tilt * bell
        spec[hmax + 1:] = 0.0
        spec[0] = 0.0
        w = np.fft.irfft(spec, 512)
        w = np.rint(w * 32767.0 / max(np.max(np.abs(w)), 1e-9)).astype(int)
        tables.append(w)
        (AUDIO / f'wave_epiano_g{group}s{s}.hex').write_text(
            ''.join(f'{int(v) & 0xFFFF:04X}\n' for v in w), encoding='ascii')
    meta.append({'group': group, 'zone': zone,
                 'midi_lo': EDGES[zone], 'midi_hi': EDGES[zone + 1] - 1,
                 'fmax_hz': round(fmax, 1), 'harmonics': hmax})

(AUDIO / 'epiano_bank_all.hex').write_text(
    ''.join(f'{int(v) & 0xFFFF:04X}\n' for t in tables for v in t), encoding='ascii')

lines = [
    '// Generated by tools/gen_epiano_bank.py from AKWF_epiano_0001 (CC0).',
    '// 12 tables = 2 zone groups x 6 stages, two tables per pROM (6 BSRAM).',
    'module gowin_prom_piano_bank(input wire clk,ce,rst, input wire [5:0] bank,',
    ' input wire [8:0] addr, output reg [15:0] dout);',
    'reg [2:0] selected=0;',
    'always @(posedge clk) if(rst) selected<=0; else if(ce) selected<=bank[3:1];',
]
for g in range(6):
    lines.append(f'wire [31:0] gd{g};')
lines += ['always @* case(selected)']
for g in range(6):
    lines.append(f" 3'd{g}: dout=gd{g}[15:0];")
lines += [' default: dout=16\'d0;', 'endcase']
for g in range(6):
    pair = np.concatenate([tables[g * 2], tables[g * 2 + 1]])
    lines.append("pROM #(.READ_MODE(1'b0),.BIT_WIDTH(6'd16),.RESET_MODE(\"SYNC\"),")
    for w in range(64):
        value = sum((int(v) & 0xFFFF) << (16 * k)
                    for k, v in enumerate(pair[w * 16:w * 16 + 16]))
        lines.append(f' .INIT_RAM_{w:02X}(256\'h{value:064X})' + (',' if w < 63 else ''))
    lines += [f' ) gp{g} (.DO(gd{g}),.AD({{bank[0],addr,4\'b0}}),',
              f' .CLK(clk),.CE(ce && bank[3:1]==3\'d{g}),.OCE(1\'b1),.RESET(rst));']
lines += ['endmodule', '']
(AUDIO / 'gowin_prom_piano_bank.v').write_text('\n'.join(lines), encoding='ascii')
(AUDIO / 'epiano_bank_meta.json').write_text(
    json.dumps({'source': 'AKWF_epiano_0001.wav', 'license': 'CC0',
                'tables': 12, 'depth': 512, 'bsram_blocks': 6,
                'bank_index': 'group*6 + stage', 'groups': meta}, indent=2) + '\n',
    encoding='utf-8')
print(json.dumps({'tables': 12, 'bsram': 6, 'groups': meta}))
