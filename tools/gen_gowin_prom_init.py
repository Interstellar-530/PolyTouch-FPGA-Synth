#!/usr/bin/env python3
"""Generate explicit Gowin pROM wrappers for the two 512-point wavetables.

The generated modules replace the behavioural arrays with the vendor primitive
so the build no longer depends on the synthesiser inferring BSRAM.  Layout per
UG285 section 3.4 (pROM, 16K block ROM):

  * BIT_WIDTH = 16 gives a 1024-deep address space, so the 512 samples occupy
    INIT_RAM_00..1F and addresses 512..1023 read back as zero,
  * each INIT_RAM word is 256 bits and holds 16 samples; sample i sits at bits
    (i % 16) * 16 of word i // 16,
  * READ_MODE = 0 selects bypass read, i.e. one clock of latency, matching the
    behavioural ROM contract used by wavetable_osc_dual_s6.

Run:  python tools/gen_gowin_prom_init.py [--hex-dir DIR] [--out-dir DIR]
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

DEPTH = 512
SAMPLES_PER_WORD = 16
WORDS = DEPTH // SAMPLES_PER_WORD          # 32 -> INIT_RAM_00..1F


def read_hex(path: Path) -> list[int]:
    words = [w.strip() for w in path.read_text(encoding="ascii").split() if w.strip()]
    if len(words) != DEPTH:
        raise ValueError(f"{path}: expected {DEPTH} entries, found {len(words)}")
    out = []
    for w in words:
        raw = int(w, 16)
        out.append(raw - 0x10000 if raw & 0x8000 else raw)
    return out


def init_words(samples: list[int]) -> list[int]:
    words = []
    for w in range(WORDS):
        value = 0
        for k in range(SAMPLES_PER_WORD):
            sample = samples[w * SAMPLES_PER_WORD + k] & 0xFFFF
            value |= sample << (k * 16)
        words.append(value)
    return words


def emit_module(name: str, source: str, digest: str, words: list[int]) -> str:
    lines = [
        "// Generated by tools/gen_gowin_prom_init.py -- do not edit by hand.",
        f"// Source: {source}  SHA256 {digest}",
        "// pROM: BIT_WIDTH=16, 1024x16 address space, 512 samples in INIT_RAM_00..1F,",
        "// READ_MODE=0 (bypass, one clock latency) to match wavetable_osc_dual_s6.",
        f"module {name} (",
        "    input  wire        clk,",
        "    input  wire        ce,",
        "    input  wire        rst,       // active-high, synchronous",
        "    input  wire [8:0]  addr,",
        "    output wire [15:0] dout",
        ");",
        "",
        "    pROM #(",
        "        .READ_MODE  (1'b0),",
        "        .BIT_WIDTH  (6'd16),",
        "        .RESET_MODE (\"SYNC\"),",
    ]
    for index, value in enumerate(words):
        lines.append(f"        .INIT_RAM_{index:02X}(256'h{value:064X}),")
    lines += [
        "        .INIT_RAM_20(256'h0), .INIT_RAM_21(256'h0), .INIT_RAM_22(256'h0),",
        "        .INIT_RAM_23(256'h0), .INIT_RAM_24(256'h0), .INIT_RAM_25(256'h0),",
        "        .INIT_RAM_26(256'h0), .INIT_RAM_27(256'h0), .INIT_RAM_28(256'h0),",
        "        .INIT_RAM_29(256'h0), .INIT_RAM_2A(256'h0), .INIT_RAM_2B(256'h0),",
        "        .INIT_RAM_2C(256'h0), .INIT_RAM_2D(256'h0), .INIT_RAM_2E(256'h0),",
        "        .INIT_RAM_2F(256'h0), .INIT_RAM_30(256'h0), .INIT_RAM_31(256'h0),",
        "        .INIT_RAM_32(256'h0), .INIT_RAM_33(256'h0), .INIT_RAM_34(256'h0),",
        "        .INIT_RAM_35(256'h0), .INIT_RAM_36(256'h0), .INIT_RAM_37(256'h0),",
        "        .INIT_RAM_38(256'h0), .INIT_RAM_39(256'h0), .INIT_RAM_3A(256'h0),",
        "        .INIT_RAM_3B(256'h0), .INIT_RAM_3C(256'h0), .INIT_RAM_3D(256'h0),",
        "        .INIT_RAM_3E(256'h0), .INIT_RAM_3F(256'h0)",
        "    ) u_prom (",
        "        .DO    (dout),",
        "        .AD    ({5'b0, addr}),",
        "        .CE    (ce),",
        "        .CLK   (clk),",
        "        .OCE   (1'b1),",
        "        .RESET (rst)",
        "    );",
        "",
        "endmodule",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    root = Path(__file__).resolve().parent.parent / "output/handoff_milestone2_20261008/source"
    parser.add_argument("--hex-dir", type=Path, default=root / "rtl/audio")
    parser.add_argument("--out-dir", type=Path, default=root / "rtl/audio")
    parser.add_argument("--json", type=Path, default=root / "rtl/audio/gowin_prom_meta.json")
    args = parser.parse_args()

    meta = {"depth": DEPTH, "words": WORDS, "tables": {}}
    for table, module in (("wave_sine", "gowin_prom_wave_sine"),
                          ("wave_bright", "gowin_prom_wave_bright")):
        hex_path = args.hex_dir / f"{table}.hex"
        payload = hex_path.read_bytes()
        digest = hashlib.sha256(payload).hexdigest()
        samples = read_hex(hex_path)
        words = init_words(samples)
        text = emit_module(module, f"rtl/audio/{table}.hex", digest, words)
        out_path = args.out_dir / f"{module}.v"
        out_path.write_text(text, encoding="ascii", newline="\n")
        meta["tables"][table] = {
            "module": module,
            "hex_sha256": digest,
            "init_words_sha256": hashlib.sha256(
                "".join(f"{w:064X}" for w in words).encode("ascii")).hexdigest(),
            "min": min(samples),
            "max": max(samples),
        }
        print(f"{out_path.name}: depth={len(samples)} min={min(samples)} max={max(samples)}")
    args.json.write_text(json.dumps(meta, indent=2, sort_keys=True) + "\n",
                         encoding="utf-8", newline="\n")
    print("meta written:", args.json)


if __name__ == "__main__":
    main()