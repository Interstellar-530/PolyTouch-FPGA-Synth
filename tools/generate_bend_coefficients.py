"""Generate the default-center Q16 bend interpolation coefficients.

Control coefficients only: this is not a waveform ROM. No BSRAM/DSP required.
"""
from pathlib import Path
import math

def anchors():
    return [round(65536 * 2 ** ((2*(adc-2048)/(2047 if adc>=2048 else 2048))/12))
            for adc in range(0,4097,128)]

def render():
    table=anchors()
    lines=['// Generated by tools/generate_bend_coefficients.py; ADC boundaries 0..4096.',
           '// The final boundary is virtual; the highest actual ADC code is 4095.',
           'function [16:0] fine_ratio_from_adc;',
           '    input [11:0] code;',
           '    reg [26:0] coefficient;',
           '    reg [16:0] product;',
           '    integer bit_index;',
           '    begin',
           '        case(code[11:7])']
    for k,(a,b) in enumerate(zip(table,table[1:])):
        lines.append(f"            5'd{k}: coefficient={{17'd{a},10'd{b-a}}};")
    lines += ["            default: coefficient={17'd65536,10'd0};",'        endcase',
              "        product=17'd64; // Round the interpolation product once.",
              '        for(bit_index=0;bit_index<7;bit_index=bit_index+1)',
              '            if(code[bit_index]) product=product+({7\'d0,coefficient[9:0]}<<bit_index);',
              '        fine_ratio_from_adc=coefficient[26:10]+(product>>7);',
              '    end','endfunction','']
    return '\n'.join(lines)

if __name__=='__main__':
    root=Path(__file__).resolve().parents[1]
    path=root/'output/handoff_milestone2_20261008/source/rtl/audio/bend_coefficients.vh'
    path.write_text(render(),encoding='ascii')
    print(path)
