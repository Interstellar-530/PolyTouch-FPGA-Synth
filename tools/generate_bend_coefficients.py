"""Generate the default-center Q16 bend interpolation coefficients.

Control coefficients only: this is not a waveform ROM. No BSRAM/DSP required.
"""
from pathlib import Path
import math

def anchors():
    return [round(65536 * 2 ** ((2*(adc-2048)/(2047 if adc>=2048 else 2048))/12))
            for adc in range(0,4097,128)]

def render():
    table=anchors()
    lines=['// Generated by tools/generate_bend_coefficients.py; ADC boundaries 0..4096.',
           '// The final boundary is virtual; the highest actual ADC code is 4095.',
           'function [26:0] fine_coefficient_from_adc;',
           '    input [11:0] code;',
           '    begin',
           '        case(code[11:7])']
    for k,(a,b) in enumerate(zip(table,table[1:])):
        lines.append(f"            5'd{k}: fine_coefficient_from_adc={{17'd{a},10'd{b-a}}};")
    lines += ["            default: fine_coefficient_from_adc={17'd65536,10'd0};",'        endcase',
              '    end','endfunction',
              'function [16:0] fine_ratio_from_adc;',
              '    input [11:0] code;',
              '    reg [26:0] coefficient;',
              '    reg [16:0] product;',
              '    integer bit_index;',
              '    begin',
              '        coefficient=fine_coefficient_from_adc(code);',
              "        product=17'd64; // Round the interpolation product once.",
              '        for(bit_index=0;bit_index<7;bit_index=bit_index+1)',
              '            if(code[bit_index]) product=product+({7\'d0,coefficient[9:0]}<<bit_index);',
              '        fine_ratio_from_adc=coefficient[26:10]+(product>>7);',
              '    end','endfunction','']
    return '\n'.join(lines)

if __name__=='__main__':
    root=Path(__file__).resolve().parents[1]
    path=root/'source/rtl/audio/bend_coefficients.vh'
    path.write_text(render(),encoding='ascii')
    table=anchors()
    reference=[table[x//128]+((table[x//128+1]-table[x//128])*(x%128)+64)//128 for x in range(4096)]
    (root/'source/sim/vectors/bend_ratio_reference.hex').write_text(
        ''.join(f'{x:05x}\n' for x in reference),encoding='ascii')
    print(path)
