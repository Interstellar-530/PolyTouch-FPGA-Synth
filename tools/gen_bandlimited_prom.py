"""Generate the 6-zone x 2-layer x 6-stage piano pROM bank."""
from pathlib import Path
import json
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
AUDIO = ROOT / 'output/handoff_milestone2_20261008/source/rtl/audio'


def main():
    profile = json.loads((AUDIO / 'piano_profiles.json').read_text(encoding='utf-8'))
    amplitudes_list = profile['relative_amplitudes']
    phases = np.asarray(profile['phase_radians'], dtype=float)
    if len(amplitudes_list) != 72:
        raise ValueError(f'expected 72 spectra, got {len(amplitudes_list)}')

    # ---- harmonic cleanup -------------------------------------------------
    # The raw Salamander extraction has outliers: 28/72 tables have a 2nd
    # harmonic above 3x the fundamental (max 45x), which makes low notes sound
    # like an octave-up buzz instead of a piano. Normalize by the fundamental,
    # cap each harmonic at 2x its median, then median-smooth across stages so
    # the six-stage morph does not step abruptly.
    raw = np.asarray(amplitudes_list, dtype=float)
    fund = np.maximum(raw[:, 0], 1e-9)
    norm = raw / fund[:, None]
    cap = np.maximum(np.median(norm, axis=0) * 2.0, 0.02)
    cap[0] = 1.0
    norm = np.minimum(norm, cap)
    arr = norm.reshape(6, 2, 6, 10)
    for z in range(6):
        for layer in range(2):
            for h in range(10):
                s = arr[z, layer, :, h].copy()
                arr[z, layer, 1:5, h] = np.median(
                    np.stack([s[0:4], s[1:5], s[2:6]]), axis=0)
    amplitudes_list = arr.reshape(72, 10).tolist()
    print('harmonic cap:', np.round(cap, 3).tolist())

    n = np.arange(512, dtype=float)
    tables = []
    for index, amplitudes in enumerate(amplitudes_list):
        amplitudes = np.asarray(amplitudes, dtype=float)
        wave = np.zeros(512, dtype=float)
        for h, (amp, phase) in enumerate(zip(amplitudes, phases), start=1):
            wave += amp * np.sin(2.0 * np.pi * h * n / 512.0 + phase)
        wave = np.rint(wave * 32767.0 / np.max(np.abs(wave))).astype(int)
        assert max(abs(wave)) <= 32767
        tables.append(wave)
        zone, remainder = divmod(index, 12)
        layer, stage = divmod(remainder, 6)
        (AUDIO / f'wave_piano_z{zone}v{layer}s{stage}.hex').write_text(
            ''.join(f'{int(v) & 0xFFFF:04X}\n' for v in wave), encoding='ascii')
    (AUDIO / 'piano_bank_all.hex').write_text(
        ''.join(f'{int(v) & 0xFFFF:04X}\n' for table in tables for v in table),
        encoding='ascii')

    lines = [
        '// Generated by tools/gen_bandlimited_prom.py.',
        '// 72 piano spectra: six pitch zones x two velocity layers x six stages.',
        '// bank = zone*12 + velocity_layer*6 + stage; paired tables share one pROM.',
        'module gowin_prom_piano_bank(input wire clk,ce,rst, input wire [6:0] bank,',
        ' input wire [8:0] addr, output reg [15:0] dout);',
        'reg [5:0] selected=0;',
        'always @(posedge clk) if(rst) selected<=0; else if(ce) selected<=bank[6:1];',
        'wire [31:0] data0,data1,data2,data3,data4,data5,data6,data7,data8,data9;',
        'wire [31:0] data10,data11,data12,data13,data14,data15,data16,data17,data18,data19;',
        'wire [31:0] data20,data21,data22,data23,data24,data25,data26,data27,data28,data29;',
        'wire [31:0] data30,data31,data32,data33,data34,data35;',
        'always @* case(selected)',
    ]
    for group in range(36):
        lines.append(f"  6'd{group}: dout=data{group}[15:0];")
    lines += ['  default: dout=16\'d0;', 'endcase']
    for group in range(36):
        pair = np.concatenate([tables[group * 2], tables[group * 2 + 1]])
        lines += ["pROM #(.READ_MODE(1'b0),.BIT_WIDTH(6'd16),.RESET_MODE(\"SYNC\"),"]
        for w in range(64):
            value = sum((int(v) & 0xFFFF) << (16 * k)
                        for k, v in enumerate(pair[w * 16:w * 16 + 16]))
            lines += [f" .INIT_RAM_{w:02X}(256'h{value:064X})" + (',' if w < 63 else '')]
        lines += [
            f') u_bank{group} (.DO(data{group}),.AD({{bank[0],addr,4\'b0}}),',
            f" .CLK(clk),.CE(ce && bank[6:1]==6'd{group}),.OCE(1'b1),.RESET(rst));"
        ]
    lines += ['endmodule', '']
    (AUDIO / 'gowin_prom_piano_bank.v').write_text('\n'.join(lines), encoding='ascii')
    metadata = {
        'zones': 6,
        'velocity_layers': 2,
        'stages': 6,
        'tables': 72,
        'depth': 512,
        'bsram_blocks': 36,
        'harmonics': 10,
        'layout': 'bank = zone*12 + velocity_layer*6 + stage',
        'peaks': [int(np.max(np.abs(t))) for t in tables],
    }
    (AUDIO / 'piano_bank_meta.json').write_text(
        json.dumps(metadata, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(metadata, indent=2))


if __name__ == '__main__':
    main()
