"""Derive octave-filtered banks from the original bright table, pack Gowin ROMs."""
from pathlib import Path
import json
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
AUDIO = ROOT/'output/handoff_milestone2_20261008/source/rtl/audio'

def main():
    original = np.array([int(x,16) for x in (AUDIO/'wave_bright.hex').read_text().split()])
    original = np.where(original>=32768, original-65536, original)
    spectrum=np.fft.rfft(original)
    banks=[]
    for h in [16,8,4,2,1]:
        filtered=spectrum.copy();filtered[h+1:]=0
        bank=original.copy() if h==16 else np.rint(np.fft.irfft(filtered,512)).astype(int)
        assert max(abs(bank))<=32767
        banks.append(bank)
        (AUDIO/f'wave_bright_h{h}.hex').write_text(''.join(f'{int(v)&65535:04X}\n' for v in bank),encoding='ascii')
    lines=['// Generated by tools/gen_bandlimited_prom.py. Five 512x16 banks in three BSRAMs.',
           'module gowin_prom_bright_bank(input wire clk,ce,rst, input wire [2:0] bank,',
           ' input wire [8:0] addr, output wire [15:0] dout);',
           'reg [1:0] selected=0;',
           'always @(posedge clk) if(rst) selected<=0; else if(ce) selected<=bank[2:1];',
           'wire [15:0] data0,data1,data2;',
           "assign dout=selected==0?data0:selected==1?data1:data2;"]
    for group in range(3):
        pair=np.concatenate([banks[group*2],banks[group*2+1] if group<2 else np.zeros(512,dtype=int)])
        lines += ["pROM #(.READ_MODE(1'b0),.BIT_WIDTH(6'd16),.RESET_MODE(\"SYNC\"),"]
        for w in range(64):
            value=sum((int(v)&65535)<<(16*k) for k,v in enumerate(pair[w*16:w*16+16]))
            lines += [f" .INIT_RAM_{w:02X}(256'h{value:064X})"+(',' if w<63 else '')]
        lines += [f') u_bank{group} (.DO(data{group}),.AD({{bank[0],addr,4\'b0}}),',
                  f" .CLK(clk),.CE(ce && bank[2:1]==2'd{group}),.OCE(1'b1),.RESET(rst));"]
    lines += ['endmodule','']
    (AUDIO/'gowin_prom_bright_bank.v').write_text('\n'.join(lines),encoding='ascii')
    metadata=dict(harmonics=[16,8,4,2,1],depth=512,bsram_blocks=3,
                  peaks=[int(max(abs(b))) for b in banks],
                  source='wave_bright.hex; identical fundamental amplitude; no per-bank normalization')
    (AUDIO/'bright_bank_meta.json').write_text(json.dumps(metadata,indent=2)+'\n',encoding='utf-8')
    print(metadata)

if __name__=='__main__':main()
