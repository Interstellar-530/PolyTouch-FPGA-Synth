#!/usr/bin/env python3
"""Regenerate gowin_prom_bright_bank.v from the six source hex tables."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AUDIO = ROOT / "output/handoff_milestone2_20261008/source/rtl/audio"
FILES = ["wave_bright_h16.hex", "wave_bright_h8.hex", "wave_bright_h4.hex",
         "wave_bright_h2.hex", "wave_bright_h1.hex", "wave_bright.hex"]
DEPTH = 512

tables = []
for name in FILES:
    words = [int(x.strip(), 16) for x in (AUDIO / name).read_text(encoding="ascii").splitlines() if x.strip()]
    if len(words) != DEPTH:
        raise RuntimeError(f"{name}: expected {DEPTH} words, got {len(words)}")
    tables.append(words)

lines = [
    "// Generated by tools/gen_bright_prom.py from wave_bright*.hex.",
    "// Six generic bright spectra in three BSRAMs; banks 0..4 are h16..h1, bank 5 is wave_bright.",
    "module gowin_prom_bright_bank(input wire clk,ce,rst, input wire [2:0] bank,",
    " input wire [8:0] addr, output wire [15:0] dout);",
    "reg [1:0] selected=0;",
    "always @(posedge clk) if(rst) selected<=0; else if(ce) selected<=bank[2:1];",
    "wire [31:0] data0,data1,data2;",
    "assign dout=selected==0?data0[15:0]:selected==1?data1[15:0]:data2[15:0];",
]
for group in range(3):
    pair = tables[group * 2] + tables[group * 2 + 1]
    lines.append("pROM #(.READ_MODE(1'b0),.BIT_WIDTH(6'd16),.RESET_MODE(\"SYNC\"),")
    for word_index in range(64):
        value = 0
        for offset, word in enumerate(pair[word_index * 16:(word_index + 1) * 16]):
            value |= (word & 0xFFFF) << (16 * offset)
        comma = "," if word_index < 63 else ""
        lines.append(f" .INIT_RAM_{word_index:02X}(256'h{value:064X}){comma}")
    lines += [
        f") u_bank{group} (.DO(data{group}),.AD({{bank[0],addr,4'b0}}),",
        f" .CLK(clk),.CE(ce && bank[2:1]==2'd{group}),.OCE(1'b1),.RESET(rst));",
    ]
lines += ["endmodule", ""]
(AUDIO / "gowin_prom_bright_bank.v").write_text("\n".join(lines), encoding="ascii")
print("wrote", AUDIO / "gowin_prom_bright_bank.v")
