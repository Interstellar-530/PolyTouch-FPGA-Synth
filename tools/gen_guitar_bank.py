"""Generate the 6-band electric-guitar pROM bank (3 BSRAMs, 512x16 each table)."""
from pathlib import Path
import argparse
import json
import numpy as np

REPO = Path(__file__).resolve().parents[1]
FS = 46875
# MIDI band edges: 0-47, 48-59, 60-66, 67-75, 76-83, 84-95
EDGES = [0, 48, 60, 67, 76, 84, 96]

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--repo-root', type=Path, default=REPO,
                    help='repository root used to resolve the default paths')
parser.add_argument('--out-dir', type=Path,
                    help='generated output directory (default: <repo-root>/output/.../rtl/audio)')
args = parser.parse_args()
ROOT = args.repo_root.resolve()
AUDIO = (args.out_dir or ROOT / 'output/handoff_milestone2_20261008/source/rtl/audio').resolve()
AUDIO.mkdir(parents=True, exist_ok=True)


def midi_f(n):
    return 440.0 * 2.0 ** ((n - 69) / 12.0)


def spectrum(max_h, pick=0.18):
    h = np.arange(1, max_h + 1, dtype=float)
    amp = np.sin(np.pi * h * pick) / h
    amp *= np.exp(-h / 10.0)
    amp *= 1.0 + 0.45 * np.exp(-((h - 3.0) / 1.5) ** 2)
    return amp


tables = []
meta_bands = []
n = np.arange(512, dtype=float)
rng = np.random.default_rng(20261019)
phases = rng.uniform(0, 2 * np.pi, 32)
for b in range(6):
    fmax = midi_f(EDGES[b + 1] - 1)
    max_h = max(1, min(24, int(0.45 * FS / fmax)))
    amp = spectrum(max_h)
    wave = np.zeros(512)
    for k, a in enumerate(amp, start=1):
        wave += a * np.sin(2 * np.pi * k * n / 512.0 + phases[k - 1])
    wave = np.rint(wave * 32767.0 / np.max(np.abs(wave))).astype(int)
    assert np.max(np.abs(wave)) <= 32767
    tables.append(wave)
    meta_bands.append({'band': b, 'midi_lo': EDGES[b], 'midi_hi': EDGES[b + 1] - 1,
                       'fmax_hz': round(fmax, 1), 'harmonics': max_h})
    (AUDIO / f'wave_guitar_b{b}.hex').write_text(
        ''.join(f'{int(v) & 0xFFFF:04X}\n' for v in wave), encoding='ascii')

(AUDIO / 'guitar_bank_all.hex').write_text(
    ''.join(f'{int(v) & 0xFFFF:04X}\n' for t in tables for v in t), encoding='ascii')

lines = [
    '// Generated by tools/gen_guitar_bank.py.',
    '// 6 band-limited electric-guitar spectra, two tables per pROM.',
    'module gowin_prom_guitar_bank(input wire clk,ce,rst, input wire [2:0] bank,',
    ' input wire [8:0] addr, output reg [15:0] dout);',
    'reg [1:0] selected=0;',
    'always @(posedge clk) if(rst) selected<=0; else if(ce) selected<=bank[2:1];',
]
for g in range(3):
    lines.append(f'wire [31:0] gd{g};')
lines += ['always @* case(selected)', '  2\'d0: dout=gd0[15:0];',
          '  2\'d1: dout=gd1[15:0];', '  default: dout=gd2[15:0];', 'endcase']
for g in range(3):
    pair = np.concatenate([tables[g * 2], tables[g * 2 + 1]])
    lines.append("pROM #(.READ_MODE(1'b0),.BIT_WIDTH(6'd16),.RESET_MODE(\"SYNC\"),")
    for w in range(64):
        value = sum((int(v) & 0xFFFF) << (16 * k)
                    for k, v in enumerate(pair[w * 16:w * 16 + 16]))
        lines.append(f' .INIT_RAM_{w:02X}(256\'h{value:064X})' + (',' if w < 63 else ''))
    lines += [f' ) gu{g} (.DO(gd{g}),.AD({{bank[0],addr,4\'b0}}),',
              f' .CLK(clk),.CE(ce && bank[2:1]==2\'d{g}),.OCE(1\'b1),.RESET(rst));']
lines += ['endmodule', '']
(AUDIO / 'gowin_prom_guitar_bank.v').write_text('\n'.join(lines), encoding='ascii')

meta = {'bands': meta_bands, 'tables': 6, 'depth': 512, 'bsram_blocks': 3,
        'harmonics': [b['harmonics'] for b in meta_bands]}
(AUDIO / 'guitar_bank_meta.json').write_text(json.dumps(meta, indent=2) + '\n',
                                             encoding='utf-8')
print(json.dumps(meta))
