#!/usr/bin/env python3
"""Generate gowin_prom_piano_bank.v from the checked-in epiano_bank_all.hex.

The original AKWF source is not required for this step because the table data is
already versioned in rtl/audio/epiano_bank_all.hex. The layout is 12 tables
(2 zone groups x 6 stages), two 512-point tables per pROM, 6 pROMs.
"""
from pathlib import Path
import argparse

REPO = Path(__file__).resolve().parent.parent
DEFAULT_AUDIO = REPO / "source/rtl/audio"
TABLES = 12
DEPTH = 512
GROUPS = TABLES // 2

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--repo-root', type=Path, default=REPO,
                    help='repository root used to resolve the default paths')
parser.add_argument('--hex', type=Path,
                    help='bank hex file (default: <repo-root>/output/.../rtl/audio/epiano_bank_all.hex)')
parser.add_argument('--out-dir', type=Path,
                    help='output directory (default: <repo-root>/output/.../rtl/audio)')
args = parser.parse_args()
ROOT = args.repo_root.resolve()
AUDIO = (args.out_dir or ROOT / 'source/rtl/audio').resolve()
HEX = (args.hex or AUDIO / 'epiano_bank_all.hex').resolve()
OUT = AUDIO / 'gowin_prom_piano_bank.v'


def main():
    words = [int(line.strip(), 16) for line in HEX.read_text(encoding="ascii").splitlines() if line.strip()]
    if len(words) != TABLES * DEPTH:
        raise RuntimeError(f"expected {TABLES * DEPTH} words, got {len(words)}")
    tables = [words[i * DEPTH:(i + 1) * DEPTH] for i in range(TABLES)]

    lines = [
        "// Generated by tools/gen_piano_prom.py from epiano_bank_all.hex.",
        "// 12 tables = 2 zone groups x 6 stages, two tables per pROM (6 BSRAM).",
        "module gowin_prom_piano_bank(input wire clk,ce,rst, input wire [5:0] bank,",
        " input wire [8:0] addr, output reg [15:0] dout);",
        "reg [2:0] selected=0;",
        "always @(posedge clk) if(rst) selected<=0; else if(ce) selected<=bank[3:1];",
    ]
    for group in range(GROUPS):
        lines.append(f"wire [31:0] gd{group};")
    lines += ["always @* case(selected)"]
    for group in range(GROUPS):
        lines.append(f" 3'd{group}: dout=gd{group}[15:0];")
    lines += [" default: dout=16'd0;", "endcase"]

    for group in range(GROUPS):
        pair = tables[group * 2] + tables[group * 2 + 1]
        lines.append("pROM #(.READ_MODE(1'b0),.BIT_WIDTH(6'd16),.RESET_MODE(\"SYNC\"),")
        for word_index in range(64):
            value = 0
            for offset, word in enumerate(pair[word_index * 16:(word_index + 1) * 16]):
                value |= (word & 0xFFFF) << (16 * offset)
            comma = "," if word_index < 63 else ""
            lines.append(f" .INIT_RAM_{word_index:02X}(256'h{value:064X}){comma}")
        lines += [
            f" ) gp{group} (.DO(gd{group}),.AD({{bank[0],addr,4'b0}}),",
            f" .CLK(clk),.CE(ce && bank[3:1]==3'd{group}),.OCE(1'b1),.RESET(rst));",
        ]
    lines += ["endmodule", ""]
    OUT.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {OUT} ({len(words)} words, {TABLES} tables, {GROUPS} pROMs)")


if __name__ == "__main__":
    main()
